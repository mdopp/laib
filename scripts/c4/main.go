// Command c4 writes the owner's two overview pages, docs/C4.md and
// docs/SICHERHEIT.md, and README.md's c4 section, from the code and the
// hand-written docs/c4.yml and docs/sicherheit.yml (owner, 2026-11-15: „Die
// sollten Teil der Dokumentation sein. Und die Aktualisierung Teil der
// Pipeline. Sie muss erfolgen!“). Same tree, same bytes: no dates, sorted.
//
//	c4             write the pages
//	c4 --check     exit 1 when a page is not what c4 writes; changes nothing
//	c4 --gate DIR  the judgment gate against main's checkout in DIR
//	c4 --issues    the daily check: a point not „läuft“ names a closed issue
//	c4 --facts     print the facts the gate compares
//
// scripts/c4.sh runs it from the repo root.
package main

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	os.Exit(run(os.Args[1:], ".", os.Stdout, os.Stderr))
}

func run(args []string, root string, out, errw io.Writer) int {
	t, err := load(root)
	if err != nil {
		fmt.Fprintln(errw, "c4:", err)
		return 2
	}
	mode := ""
	if len(args) > 0 {
		mode = args[0]
	}
	switch {
	case mode == "--gate" && len(args) == 2:
		base, err := load(args[1])
		if err != nil {
			fmt.Fprintln(errw, "c4: main's checkout:", err)
			return 2
		}
		return gate(t, base, strings.Split(os.Getenv("C4_LABELS"), ","), errw)
	case mode == "--issues":
		return issues(t, out)
	case mode == "--facts":
		for _, f := range facts(t) {
			fmt.Fprintf(out, "%s\t%s\n", f.key, f.val)
		}
		return 0
	case mode == "" || mode == "--check":
		return write(t, root, mode == "--check", out, errw)
	}
	fmt.Fprintln(errw, "usage: scripts/c4.sh [--check | --gate <main's checkout> | --issues | --facts]")
	return 2
}

const (
	begin = "<!-- c4:begin -->"
	end   = "<!-- c4:end -->"
)

// pages are the files c4 writes, path → content.
func pages(t *tree, root string) (map[string][]byte, error) {
	readme, err := os.ReadFile(filepath.Join(root, "README.md"))
	if err != nil {
		return nil, err
	}
	i, j := bytes.Index(readme, []byte(begin+"\n")), bytes.Index(readme, []byte(end+"\n"))
	if i < 0 || j < i {
		return nil, fmt.Errorf("README.md has no %s … %s", begin, end)
	}
	var r bytes.Buffer
	r.Write(readme[:i])
	r.WriteString(readmeSection(t))
	r.Write(readme[j:])
	return map[string][]byte{
		"docs/C4.md":         []byte(c4page(t)),
		"docs/SICHERHEIT.md": []byte(secpage(t)),
		"README.md":          r.Bytes(),
	}, nil
}

func write(t *tree, root string, check bool, out, errw io.Writer) int {
	if errs := validate(t); len(errs) > 0 {
		for _, e := range errs {
			fmt.Fprintln(errw, "c4:", e)
		}
		return 2
	}
	want, err := pages(t, root)
	if err != nil {
		fmt.Fprintln(errw, "c4:", err)
		return 2
	}
	var stale []string
	for _, p := range sortedKeys(want) {
		have, _ := os.ReadFile(filepath.Join(root, p))
		if bytes.Equal(have, want[p]) {
			continue
		}
		stale = append(stale, p)
		if check {
			fmt.Fprintf(errw, "c4: %s veraltet, zuerst anders in Zeile %d\n", p, firstDiff(have, want[p]))
		} else if err := os.WriteFile(filepath.Join(root, p), want[p], 0o644); err != nil {
			fmt.Fprintln(errw, "c4:", err)
			return 2
		}
	}
	switch {
	case len(stale) == 0:
		fmt.Fprintln(out, "c4: docs/C4.md, docs/SICHERHEIT.md und README.md sind aktuell")
	case check:
		fmt.Fprintln(errw, "c4: die Übersichtsseiten sind aus dem Code erzeugt und passen nicht mehr zu ihm. Führe scripts/c4.sh aus und committe "+strings.Join(stale, ", ")+" mit.")
		return 1
	default:
		fmt.Fprintln(out, "c4: geschrieben:", strings.Join(stale, ", "))
	}
	return 0
}

func firstDiff(a, b []byte) int {
	la, lb := strings.Split(string(a), "\n"), strings.Split(string(b), "\n")
	for i := range min(len(la), len(lb)) {
		if la[i] != lb[i] {
			return i + 1
		}
	}
	return min(len(la), len(lb)) + 1
}

// readmeSection is README.md's c4 part: the three layers, the context and
// the services, the security concept in short. English, as README is.
func readmeSection(t *tree) string {
	var b md
	b.WriteString(begin + "\n<!-- generated by scripts/c4.sh from docs/c4.yml, docs/sicherheit.yml and templates/; edit those, not this part -->\n\n")
	b.p("Three layers by purpose (ADR 0035), dependencies pointing down only. **Layer 0 · Laib** keeps the box alive, safe and reachable: ring **0a** is the trust kernel on the host (approval, keys, rights, apply, journal), ring **0b** Laib's helpers in containers with their own tokens and no age key, and the foundation services. **Layer 1 · building blocks** are standard programs that hold data or give a capability. **Layer 2 · value** is what gives the family something, built on the blocks: Homes, the archive and own apps, each a program of its own that reaches the box only through interfaces. The full map with the kernel's inside and the household's data is [`docs/C4.md`](docs/C4.md); the security concept is [`docs/SICHERHEIT.md`](docs/SICHERHEIT.md).")
	b.p("### Context")
	b.mermaid(t.c4.Kontext.Mermaid)
	b.p("### Services and who needs whom")
	b.p("Each template in its layer; solid arrows are `after:`, dashed `uses:` and `instances:`, double the door to Laib.")
	b.mermaid(containers(t))
	b.p("### Security in short")
	var items []string
	for _, g := range t.sec.Grundsaetze {
		items = append(items, g.En)
	}
	b.list(items)
	b.mermaid(t.sec.Zonen.Mermaid)
	b.p("Routes, ports, hands, secrets, the host-network exceptions and what still ties layer 2 to the OS: [`docs/SICHERHEIT.md`](docs/SICHERHEIT.md), generated from the code.")
	return strings.TrimRight(b.String(), "\n") + "\n"
}
