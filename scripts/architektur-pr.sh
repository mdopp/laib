#!/usr/bin/env sh
# The daily README update (.github/workflows/architektur.yml): runs
# scripts/architektur.sh on main and, when README.md's architecture section
# changed, opens one pull request from the fixed branch bot/architektur, or
# updates the open one. The branch is main plus that one docs(readme)
# commit, rebuilt every run, so release-please cuts no release and nothing
# lands on main without a merge. When main is current again, an open PR of
# that branch is closed. Needs git, gh and GH_TOKEN with contents and
# pull-requests: write.
set -e
cd "$(dirname "$0")/.."
branch=bot/architektur
scripts/architektur.sh
open=$(gh pr list --head "$branch" --state open --json number --jq '.[0].number // empty')
if git diff --quiet -- README.md; then
  echo "architektur-pr: README.md is current"
  [ -z "$open" ] || gh pr close "$open" --delete-branch --comment "main's README.md is current again; nothing to update."
  exit 0
fi
# the open PR carries this very section already: no new commit, no churn
if [ -n "$open" ] && git fetch -q origin "$branch" && git diff --quiet "origin/$branch" -- README.md; then
  echo "architektur-pr: #$open already carries this section"
  exit 0
fi
git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
git switch -C "$branch"
git commit -q -m "docs(readme): bring the architecture section up to date" -m "Generated by scripts/architektur.sh: the lines and caps of scripts/loc.sh and the services of templates/." -- README.md
git push -q --force origin "$branch"
if [ -n "$open" ]; then
  echo "architektur-pr: updated #$open"
else
  gh pr create --base main --head "$branch" --title "docs(readme): bring the architecture section up to date" \
    --body "The daily run of \`scripts/architektur.sh\` (\`.github/workflows/architektur.yml\`) found README.md's architecture section stale: lines and caps from \`scripts/loc.sh\`, services from \`templates/*/laib.yml\` and \`values.example.yml\`. This branch is main plus that one commit; the next run rebuilds it, and closes this PR when main is current again."
fi
