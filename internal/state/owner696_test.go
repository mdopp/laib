package state

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// #696: owner: is for a key from outside only, and carries the page's words.
func TestOwnerIsForAnExternalKeyWithItsWords(t *testing.T) {
	for _, c := range []struct{ secret, err string }{
		{"{name: K, external: true, owner: {label: L, warum: W, hilfe: H, link: \"https://x.example\"}}", ""},
		{"{name: K, owner: {label: L, warum: W, hilfe: H}}", "owner:"},                                     // generated by the box
		{"{name: K, external: true, mint: haus, owner: {label: L, warum: W, hilfe: H}}", "owner:"},         // a Laib token
		{"{name: K, external: true, owner: {label: L, hilfe: H}}", "owner:"},                               // no warum
		{"{name: K, external: true, owner: {label: L, warum: W, hilfe: H, link: \"http://x\"}}", "owner:"}, // not https
	} {
		dir := t.TempDir()
		if err := os.CopyFS(dir, os.DirFS("../../testdata/golden/basic/state")); err != nil {
			t.Fatal(err)
		}
		f := filepath.Join(dir, "services", "whoami", "laib.yml")
		b, _ := os.ReadFile(f)
		os.WriteFile(f, []byte(strings.Replace(string(b), "secrets:\n", "secrets:\n  - "+c.secret+"\n", 1)), 0o644)
		_, err := Load(dir)
		if c.err == "" && err != nil || c.err != "" && (err == nil || !strings.Contains(err.Error(), c.err)) {
			t.Errorf("%s: %v, want %q", c.secret, err, c.err)
		}
	}
}
