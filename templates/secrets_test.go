package templates

import (
	"os"
	"path/filepath"
	"testing"

	"gopkg.in/yaml.v3"
)

// #166: an external secret the service works without must say optional:
// true, or `laib add` refuses until someone sets it (cmd/laib applyHeld).
func TestSecretsTheServiceWorksWithoutAreOptional(t *testing.T) {
	for svc, names := range map[string][]string{
		"bote":            {"BOTE_MODEL_KEY", "BOTE_HA_TOKEN", "USAGE_METRICS_TOKEN"},                                                 // a cloud model only; without HA the ha tool is absent (README); without usage-metrics nothing is counted (#266)
		"haus":            {"HAUS_HA_TOKEN", "HAUS_RADICALE_PASSWORD", "HAUS_PAPERLESS_TOKEN", "BOTE_API_KEY", "USAGE_METRICS_TOKEN"}, // without it the house paths stay on the Solaris bridge (haus#10); without the Bote no Sprechen field (#215); without usage-metrics nothing is counted (#266)
		"home-assistant":  {"BOTE_NOTIFY_TOKEN", "HA_MUSIC_ASSISTANT_TOKEN"},                                                          // generated by laib add bote; without the Bote rest_command.mitteilung is refused (#177); without Music Assistant no integration (#526)
		"music-assistant": {"JELLYFIN_ADMIN_PASSWORD", "HA_MUSIC_ASSISTANT_TOKEN"},                                                    // without media no Jellyfin source; the token is minted by its own post-deploy (#526)
		"stimme":          {"STIMME_HA_TOKEN"},                                                                                        // minted by home-assistant's post-deploy; without HA Whisper has no names
	} {
		b, err := os.ReadFile(filepath.Join(svc, "laib.yml"))
		if err != nil {
			t.Fatal(err)
		}
		var c struct {
			Secrets []struct {
				Name     string `yaml:"name"`
				External bool   `yaml:"external"`
				Optional bool   `yaml:"optional"`
			} `yaml:"secrets"`
		}
		if err := yaml.Unmarshal(b, &c); err != nil {
			t.Fatal(err)
		}
		for _, want := range names {
			found := false
			for _, s := range c.Secrets {
				if s.Name == want {
					found = true
					if !s.External || !s.Optional {
						t.Errorf("%s: %s must be external and optional: laib add %s refuses without it", svc, want, svc)
					}
				}
			}
			if !found {
				t.Errorf("%s: %s is not declared", svc, want)
			}
		}
	}
}
